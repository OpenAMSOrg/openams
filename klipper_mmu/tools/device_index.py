"""Regenerate (or check) docs/devices/README.md, the one-table index of every device dossier."""

import argparse
import json
import sys
from pathlib import Path

def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Check if README.md is up to date")
    parser.add_argument("--dir", default="docs/devices", help="Directory containing device dossiers")
    args = parser.parse_args()

    dir_path = Path(args.dir)
    readme_path = dir_path / "README.md"

    files = sorted(dir_path.glob("*.json"))

    lines = [
        "# Device dossiers",
        "",
        "Each device page is generated from Happy Hare's own harness by "
        "`tools/upstream_dossier.py`: the per-device behaviour spec, with the decisions "
        "we made about it. This index is generated by `tools/device_index.py`, so edit the "
        "dossiers, not this file.",
        "",
        "| Device | Gates | Arrival | Buffer | Preload rest | Unload rest | Decisions |",
        "|---|---|---|---|---|---|---|",
    ]

    for f in files:
        dossier = json.loads(f.read_text())

        name = f.stem
        gates = dossier.get("device", {}).get("gates", "-")

        arrival = "-"
        moves = dossier.get("operations", {}).get("load", {}).get("moves", [])
        for move in reversed(moves):
            if move.get("homing"):
                endstop = move.get("endstop")
                if endstop:
                    arrival = endstop
                break

        buffer_val = "none"
        hw = dossier.get("hardware", {})
        if "mmu_buffer unit0" in hw:
            buf_sec = hw["mmu_buffer unit0"]
            if "analog_pin" in buf_sec:
                buffer_val = "analog"
            elif "tension_pin" in buf_sec or "compression_pin" in buf_sec:
                buffer_val = "switched"

        def format_rest(op: str) -> str:
            end = dossier.get("operations", {}).get(op, {}).get("end", {})
            sensor = end.get("sensor")
            offset = end.get("offset")
            if sensor is None or offset is None:
                return "-"
            return f"{sensor} {offset:+.1f}"

        preload_rest = format_rest("preload")
        unload_rest = format_rest("unload")
        decisions = len(dossier.get("decisions", []))

        lines.append(f"| [{name}]({name}.md) | {gates} | {arrival} | {buffer_val} | {preload_rest} | {unload_rest} | {decisions} |")

    content = "\n".join(lines) + "\n"

    if args.check:
        if not readme_path.exists() or readme_path.read_text() != content:
            print(f"stale: {readme_path}")
            return 1
        return 0

    readme_path.write_text(content)
    return 0

if __name__ == "__main__":
    sys.exit(main())
